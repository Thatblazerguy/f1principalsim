export function getCircuitById(circuitId) {
  return CIRCUIT_LIBRARY.find(c => c.circuitId === circuitId) || null;
}

export function getCircuitsByRegion(region) {
  return CIRCUIT_LIBRARY.filter(c => c.region === region);
}

export function getCircuitsByType(type) {
  return CIRCUIT_LIBRARY.filter(c => c.type === type);
}

export function searchCircuits(query, filters = {}) {
  let results = [...CIRCUIT_LIBRARY];
  if (query) {
    const q = query.toLowerCase();
    results = results.filter(c =>
      c.name.toLowerCase().includes(q) ||
      c.country.toLowerCase().includes(q) ||
      c.region.toLowerCase().includes(q) ||
      (c.grandPrix || '').toLowerCase().includes(q) ||
      (c.keyCharacteristics || []).some(k => k.toLowerCase().includes(q))
    );
  }
  if (filters.region) results = results.filter(c => c.region === filters.region);
  if (filters.type) results = results.filter(c => c.type === filters.type);
  if (filters.licensed !== undefined) results = results.filter(c => c.licensed === filters.licensed);
  if (filters.calendarStatus) results = results.filter(c => c.calendarStatus === filters.calendarStatus);
  if (filters.minDifficulty !== undefined) results = results.filter(c => (c.overtakingDifficulty || 50) >= filters.minDifficulty);
  if (filters.maxDifficulty !== undefined) results = results.filter(c => (c.overtakingDifficulty || 50) <= filters.maxDifficulty);
  if (filters.minTyreDeg !== undefined) results = results.filter(c => (c.perf?.tyreDegradation || 5) >= filters.minTyreDeg);
  return results;
}

